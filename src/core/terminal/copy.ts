/** 터미널에서 복사할 때 클립보드에 쓸 글자. `null` 은 "쓸 것이 없으니 건드리지 말라" 는 뜻이다.
 *
 *  **왜 두 개를 받는가.** xterm 의 선택은 화면 좌표를 가리킬 뿐 글자를 붙잡지 않는다. 좌표는
 *  그대로 둔 채 그 자리의 내용만 바뀔 수 있고, claude 같은 full-screen TUI 는 매 프레임 화면을
 *  다시 그리므로 실제로 늘 바뀐다. 드래그해서 고른 글자가 Cmd+C 를 누를 때쯤 그 좌표에 없는
 *  것이다. 그러면서 `hasSelection()` 은 계속 true 라 하이라이트는 그 자리에 남아 있어서, 고른
 *  글자가 거기 있다고 믿을 수밖에 없다.
 *
 *  그래서 `latched` — 선택이 만들어지던 순간(`onSelectionChange`)에 붙잡아 둔 글자 — 가 먼저고,
 *  지금 좌표에서 읽히는 `live` 는 그것이 없을 때의 차선이다.
 *
 *  **그리고 공백으로는 덮어쓰지 않는다.** 다시 그려진 자리에서 읽히는 것은 빈 문자열이 아니라
 *  줄바꿈과 공백이고, 그래서 예전의 `if (sel)` 을 통과해 그대로 클립보드에 쓰였다. 복사한
 *  사람에게는 다른 앱에 붙여넣어도 아무것도 나오지 않는 것으로 보인다 — 붙여넣기가 고장 난 것이
 *  아니라 클립보드가 공백으로 지워진 것이다. 쓸 것이 없으면 이전 클립보드를 그대로 둔다.
 *
 *  판단에만 `trim` 을 쓰고 돌려줄 때는 원본 그대로다. 들여쓰기가 지워진 코드 조각은 붙여넣어도
 *  쓸 수 없다. */
export function copyTextFor(latched: string, live: string): string | null {
  if (latched.trim()) return latched
  if (live.trim()) return live
  return null
}
